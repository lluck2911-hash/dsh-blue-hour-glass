import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const moduleId = process.argv[2] || pkg.name;
const imagePath = process.argv[4] ? path.resolve(process.argv[4]) : path.join(root, 'assets/beach-bg.jpg');
const mime = imagePath.endsWith('.svg') ? 'image/svg+xml' : 'image/jpeg';
const image = fs.readFileSync(imagePath).toString('base64');
const base = fs.readFileSync(path.join(root, 'src/theme.css'), 'utf8').replace('__BLUE_HOUR_WALLPAPER__', `data:${mime};base64,${image}`);
if (base.includes('__BLUE_HOUR_WALLPAPER__')) throw new Error('Unresolved wallpaper token');
const css = base + '\n' + fs.readFileSync(path.join(root, 'src/lighting.css'), 'utf8') + '\n' + fs.readFileSync(path.join(root, 'src/interactions.css'), 'utf8');
const mount = fs.readFileSync(path.join(root, 'src/mount-theme.js'), 'utf8').replace('export function mountTheme', 'function mountTheme');
const client = `// Blue Hour Glass ${pkg.version}; generated by scripts/build.mjs.\nwindow.__ModuleLoader__.load({id:${JSON.stringify(moduleId)},factory(require){\n${mount}\nreturn {apply(ctx){mountTheme(ctx,${JSON.stringify(css)},${JSON.stringify(moduleId)});}};\n}});\n`;
const output = process.argv[3] ? path.resolve(process.argv[3]) : path.join(root, 'client.js');
fs.writeFileSync(output, client);
console.log(`Built ${pkg.name}@${pkg.version} (${Buffer.byteLength(client)} bytes)`);
